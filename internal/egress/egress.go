// AllowlistContainerPath is where the composed allowlist is mounted in the
// sidecar.
const AllowlistContainerPath = "/etc/squid/ais-allowlist"

// Dir is where the rendered squid.conf and generated.acl live.
func Dir(cfg *config.Config) string { return filepath.Join(cfg.StateDir(), "egress") }

// GeneratedPath is the composed allowlist squid reads.
func GeneratedPath(cfg *config.Config) string { return filepath.Join(Dir(cfg), "generated.acl") }

// SquidConfPath is the rendered squid.conf on the host.
func SquidConfPath(cfg *config.Config) string { return filepath.Join(Dir(cfg), "squid.conf") }

// ExtraPath is the one hand-editable fragment, for ad-hoc `ais egress allow`.
func ExtraPath(cfg *config.Config) string {
	return filepath.Join(filepath.Dir(config.ExpandPath(cfg.Paths.TasksDir)), "egress-extra.acl")
}

// SquidConf renders the sidecar configuration.
func SquidConf(cfg *config.Config) (string, error) {
	tmpl, err := template.New("squid").Parse(string(assets.Read("squid.conf.tmpl")))
	if err != nil {
		return "", err
	}
	var b strings.Builder
	err = tmpl.Execute(&b, map[string]any{
		"Port":          cfg.Egress.ProxyPort,
		"ProxyName":     ProxyContainer,
		"Subnet":        cfg.Egress.Subnet,
		"AllowlistPath": AllowlistContainerPath,
	})
	return b.String(), err
}

// ValidateDomain accepts "example.com" (exact host) or ".example.com" (the
// domain and every subdomain, squid dstdomain semantics).
func ValidateDomain(d string) error {
	if d == "" {
		return fmt.Errorf("empty domain")
	}
	for _, r := range d {
		if !(r == '.' || r == '-' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')) {
			return fmt.Errorf("%q does not look like a domain", d)
		}
	}
	return nil
}

// Compose builds the generated allowlist:
//
//	embedded claude list + config baseAllowlist + every task's egress.allow
//	+ the extra.acl file → validate → deduplicate
func Compose(cfg *config.Config, tasks []*task.Task) (string, error) {
	var b strings.Builder
	b.WriteString("# Generated by ais. Do not edit: task files, config egress.baseAllowlist\n")
	b.WriteString("# and " + ExtraPath(cfg) + " are the sources.\n")
	seen := map[string]bool{}
	section := func(label string, entries []string) error {
		fmt.Fprintf(&b, "\n# --- %s ---\n", label)
		for _, e := range entries {
			e = strings.TrimSpace(e)
			if e == "" || strings.HasPrefix(e, "#") {
				continue
			}
			if err := ValidateDomain(e); err != nil {
				return fmt.Errorf("%s: %w", label, err)
			}
			if seen[e] {
				continue
			}
			seen[e] = true
			b.WriteString(e + "\n")
		}
		return nil
	}
	if err := section("claude", strings.Split(string(assets.Read("allowlists/claude.txt")), "\n")); err != nil {
		return "", err
	}
	if err := section("base", strings.Split(string(assets.Read("allowlists/base.txt")), "\n")); err != nil {
		return "", err
	}
	if err := section("config", cfg.Egress.BaseAllow); err != nil {
		return "", err
	}
	for _, t := range tasks {
		if !t.IsEnabled() && len(t.Egress.Allow) == 0 {
			continue
		}
		if err := section("task "+t.Name, t.Egress.Allow); err != nil {
			return "", err
		}
	}
	if data, err := os.ReadFile(ExtraPath(cfg)); err == nil {
		if err := section("extra", strings.Split(string(data), "\n")); err != nil {
			return "", err
		}
	}
	return b.String(), nil
}

// Reachable lists the hosts one task can fetch through the proxy, in the
// order of Compose without the claude section and without other tasks:
// embedded base list, config baseAllowlist, the task's egress.allow and the
// extra.acl file. The runner tells the model this list.
func Reachable(cfg *config.Config, t *task.Task) []string {
	seen := map[string]bool{}
	var out []string
	add := func(entries []string) {
		for _, e := range entries {
			e = strings.TrimSpace(e)
			if e == "" || strings.HasPrefix(e, "#") || seen[e] {
				continue
			}
			seen[e] = true
			out = append(out, e)
		}
	}
	add(strings.Split(string(assets.Read("allowlists/base.txt")), "\n"))
	add(cfg.Egress.BaseAllow)
	add(t.Egress.Allow)
	if data, err := os.ReadFile(ExtraPath(cfg)); err == nil {
		add(strings.Split(string(data), "\n"))
	}
	return out
}

// Entries counts non-comment, non-blank lines in an allowlist file.
func Entries(path string) int {
	data, err := os.ReadFile(path)
	if err != nil {
		return 0
	}
	n := 0
	for _, line := range strings.Split(string(data), "\n") {
		t := strings.TrimSpace(line)
		if t != "" && !strings.HasPrefix(t, "#") {
			n++
		}
	}
	return n
}

// AddExtra appends domains to the extra fragment.
func AddExtra(cfg *config.Config, domains []string) error {
	for _, d := range domains {
		if err := ValidateDomain(d); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(filepath.Dir(ExtraPath(cfg)), 0o700); err != nil {
		return err
	}
	f, err := os.OpenFile(ExtraPath(cfg), os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0o644)
	if err != nil {
		return err
	}
	defer f.Close()
	for _, d := range domains {
		if _, err := fmt.Fprintln(f, d); err != nil {
			return err
		}
	}
	return nil
}

// RemoveExtra drops domains from the extra fragment.
func RemoveExtra(cfg *config.Config, domains []string) (int, error) {
	data, err := os.ReadFile(ExtraPath(cfg))
	if os.IsNotExist(err) {
		return 0, nil
	}
	if err != nil {
		return 0, err
	}
	drop := map[string]bool{}
	for _, d := range domains {
		drop[strings.TrimSpace(d)] = true
	}
	var keep []string
	removed := 0
	for _, line := range strings.Split(strings.TrimRight(string(data), "\n"), "\n") {
		if drop[strings.TrimSpace(line)] {
			removed++
			continue
		}
		keep = append(keep, line)
	}
	out := strings.Join(keep, "\n")
	if out != "" {
		out += "\n"
	}
	return removed, os.WriteFile(ExtraPath(cfg), []byte(out), 0o644)
}

// ParseDenied counts denied requests per host from squid's access log.
func ParseDenied(logs string) map[string]int {
	counts := map[string]int{}
	for _, line := range strings.Split(logs, "\n") {
		if host, denied, ok := ParseAccess(line); ok && denied {
			counts[host]++
		}
	}
	return counts
}

// ParseAccess extracts the destination host and the verdict from one squid
// native access-log line. ok is false for anything that is not an access
// line.
func ParseAccess(line string) (host string, denied, ok bool) {
	fields := strings.Fields(line)
	if len(fields) < 7 {
		return "", false, false
	}
	if _, err := strconv.ParseFloat(fields[0], 64); err != nil {
		return "", false, false
	}
	if !strings.Contains(fields[3], "/") {
		return "", false, false
	}
	denied = strings.Contains(fields[3], "DENIED")
	u := fields[6]
	if i := strings.Index(u, "://"); i >= 0 {
		u = u[i+3:]
	}
	if i := strings.IndexByte(u, '/'); i >= 0 {
		u = u[:i]
	}
	if i := strings.LastIndex(u, ":"); i > 0 {
		u = u[:i]
	}
	if u == "" {
		return "", false, false
	}
	return u, denied, true
}

// Manager brings the topology up and keeps the allowlist current.
type Manager struct {
	Cfg     *config.Config
	RT      runtime.Runtime
	SELinux bool
	Info    func(format string, args ...any)
}

func (m *Manager) info(format string, args ...any) {
	if m.Info != nil {
		m.Info(format, args...)
	}
}

// WriteFiles renders squid.conf and the composed allowlist. Both are
// overwritten in place, never renamed: they are bind-mounted into the
// sidecar and a rename would leave it reading a dead inode.
func (m *Manager) WriteFiles(tasks []*task.Task) (changed bool, err error) {
	if err := os.MkdirAll(Dir(m.Cfg), 0o755); err != nil {
		return false, err
	}
	acl, err := Compose(m.Cfg, tasks)
	if err != nil {
		return false, err
	}
	if old, _ := os.ReadFile(GeneratedPath(m.Cfg)); string(old) != acl {
		changed = true
		if err := os.WriteFile(GeneratedPath(m.Cfg), []byte(acl), 0o644); err != nil {
			return false, err
		}
	}
	conf, err := SquidConf(m.Cfg)
	if err != nil {
		return changed, err
	}
	if old, _ := os.ReadFile(SquidConfPath(m.Cfg)); string(old) != conf {
		changed = true
		if err := os.WriteFile(SquidConfPath(m.Cfg), []byte(conf), 0o644); err != nil {
			return changed, err
		}
	}
	return changed, nil
}

// EnsureNetworks creates the two networks when missing.
func (m *Manager) EnsureNetworks(ctx context.Context) error {
	labels := container.BaseLabels(container.RoleNetwork)
	if exists, _ := m.RT.NetworkExists(ctx, InternalNetwork); !exists {
		if err := m.RT.NetworkCreate(ctx, InternalNetwork, true, m.Cfg.Egress.Subnet, labels); err != nil {
			return err
		}
		m.info("created internal network %s (%s)", InternalNetwork, m.Cfg.Egress.Subnet)
	}
	if exists, _ := m.RT.NetworkExists(ctx, EgressNetwork); !exists {
		if err := m.RT.NetworkCreate(ctx, EgressNetwork, false, "", labels); err != nil {
			return err
		}
		m.info("created network %s", EgressNetwork)
	}
	return nil
}

// ProxySpec is the squid sidecar container.
func (m *Manager) ProxySpec() (*container.Spec, error) {
	ip, err := ProxyIP(m.Cfg.Egress.Subnet)
	if err != nil {
		return nil, err
	}
	return &container.Spec{
		Image:  m.Cfg.Egress.ProxyImage,
		Name:   ProxyContainer,
		Detach: true,
		Mounts: []container.Mount{
			{Type: container.MountBind, Source: SquidConfPath(m.Cfg), Dest: "/etc/squid/squid.conf", Options: []string{"ro"}},
			{Type: container.MountBind, Source: GeneratedPath(m.Cfg), Dest: AllowlistContainerPath, Options: []string{"ro"}},
		},
		NoNewPrivileges: true,
		PidsLimit:       256,
		// The sidecar sits on both networks: the internal one it serves (at a
		// fixed address so clients never need DNS) and an ordinary one that
		// is its way out.
		Networks: []container.NetworkAttach{{Name: InternalNetwork, IP: ip}, {Name: EgressNetwork}},
		Labels:   container.BaseLabels(container.RoleProxy),
	}, nil
}

// Ensure brings networks and the proxy up, or reloads a running proxy when
// the allowlist changed.
func (m *Manager) Ensure(ctx context.Context, tasks []*task.Task) error {
	if err := m.EnsureNetworks(ctx); err != nil {
		return err
	}
	changed, err := m.WriteFiles(tasks)
	if err != nil {
		return err
	}
	if running, _ := m.RT.ContainerRunning(ctx, ProxyContainer); running {
		if changed {
			return m.Reload(ctx, tasks)
		}
		return nil
	}
	if exists, _ := m.RT.ContainerExists(ctx, ProxyContainer); exists {
		_ = m.RT.Remove(ctx, ProxyContainer, runtime.RemoveOptions{Force: true})
	}
	spec, err := m.ProxySpec()
	if err != nil {
		return err
	}
	if exists, _ := m.RT.ImageExists(ctx, m.Cfg.Egress.ProxyImage); !exists {
		m.info("pulling proxy image %s (first time only)", m.Cfg.Egress.ProxyImage)
	}
	if err := m.RT.RunDetached(ctx, spec.Argv(m.RT.Dialect(), m.SELinux)); err != nil {
		return fmt.Errorf("could not start the egress proxy %s: %w", ProxyContainer, err)
	}
	m.info("egress proxy %s up, allowlist %s (%d entries)", ProxyContainer, GeneratedPath(m.Cfg), Entries(GeneratedPath(m.Cfg)))
	return nil
}

// Reload re-composes the allowlist and applies it, gated on `squid -k
// parse`: the previous allowlist is restored when the new one is rejected.
func (m *Manager) Reload(ctx context.Context, tasks []*task.Task) error {
	previous, _ := os.ReadFile(GeneratedPath(m.Cfg))
	if _, err := m.WriteFiles(tasks); err != nil {
		return err
	}
	if running, _ := m.RT.ContainerRunning(ctx, ProxyContainer); !running {
		m.info("proxy not running; configuration applies on the next start")
		return nil
	}
	res, err := m.RT.Exec(ctx, ProxyContainer, []string{"squid", "-k", "parse"})
	if err != nil {
		return err
	}
	if res.ExitCode != 0 {
		if previous != nil {
			_ = os.WriteFile(GeneratedPath(m.Cfg), previous, 0o644)
		}
		return fmt.Errorf("squid rejected the new configuration, previous allowlist restored:\n%s", strings.TrimSpace(res.Stderr))
	}
	if _, err := m.RT.Exec(ctx, ProxyContainer, []string{"squid", "-k", "reconfigure"}); err != nil {
		return err
	}
	m.info("proxy reloaded (%d entries)", Entries(GeneratedPath(m.Cfg)))
	return nil
}

// Remove stops the proxy and removes both networks.
func (m *Manager) Remove(ctx context.Context) error {
	for _, name := range []string{ProxyContainer, BackendContainer} {
		if exists, _ := m.RT.ContainerExists(ctx, name); exists {
			if err := m.RT.Remove(ctx, name, runtime.RemoveOptions{Force: true}); err != nil {
				return err
			}
			m.info("removed %s", name)
		}
	}
	for _, n := range []string{InternalNetwork, EgressNetwork} {
		if exists, _ := m.RT.NetworkExists(ctx, n); exists {
			if err := m.RT.NetworkRemove(ctx, n); err != nil {
				return err
			}
			m.info("removed network %s", n)
		}
	}
	return nil
}

// Status describes the topology.
type Status struct {
	Subnet   string            `json:"subnet"`
	Networks map[string]bool   `json:"networks"`
	Proxy    SidecarStatus     `json:"proxy"`
	Backend  SidecarStatus     `json:"backend"`
	Entries  int               `json:"allowlistEntries"`
	Files    map[string]string `json:"files"`
}

// SidecarStatus is one sidecar's state.
type SidecarStatus struct {
	Name  string `json:"name"`
	State string `json:"state"`
	IP    string `json:"ip"`
}

// GetStatus inspects the topology.
func (m *Manager) GetStatus(ctx context.Context) Status {
	st := Status{Subnet: m.Cfg.Egress.Subnet, Networks: map[string]bool{}, Files: map[string]string{
		"squidConf": SquidConfPath(m.Cfg), "allowlist": GeneratedPath(m.Cfg), "extra": ExtraPath(m.Cfg),
	}}
	for _, n := range []string{InternalNetwork, EgressNetwork} {
		ok, _ := m.RT.NetworkExists(ctx, n)
		st.Networks[n] = ok
	}
	state := func(name string) string {
		if running, _ := m.RT.ContainerRunning(ctx, name); running {
			return "running"
		}
		if ex, _ := m.RT.ContainerExists(ctx, name); ex {
			return "stopped"
		}
		return "absent"
	}
	pip, _ := ProxyIP(m.Cfg.Egress.Subnet)
	bip, _ := BackendIP(m.Cfg.Egress.Subnet)
	st.Proxy = SidecarStatus{Name: ProxyContainer, State: state(ProxyContainer), IP: pip}
	st.Backend = SidecarStatus{Name: BackendContainer, State: state(BackendContainer), IP: bip}
	st.Entries = Entries(GeneratedPath(m.Cfg))
	return st
}

// Denied aggregates denied hosts from the proxy log.
func (m *Manager) Denied(ctx context.Context, tail int) ([]DeniedHost, error) {
	logs, err := m.RT.Logs(ctx, ProxyContainer, tail)
	if err != nil {
		return nil, err
	}
	counts := ParseDenied(logs)
	out := make([]DeniedHost, 0, len(counts))
	for h, n := range counts {
		out = append(out, DeniedHost{Host: h, Count: n})
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Count != out[j].Count {
			return out[i].Count > out[j].Count
		}
		return out[i].Host < out[j].Host
	})
	return out, nil
}

// DeniedHost is one aggregated denial.
type DeniedHost struct {
	Host  string `json:"host"`
	Count int    `json:"count"`
}
